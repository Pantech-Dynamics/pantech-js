// Regenerates the types from the vendored public API spec:
//   src/types.gen.ts   paths, components and operations (openapi-typescript)
//   src/models.gen.ts  one named alias per schema, e.g. `Instance`
// Operations in scripts/not-in-sdk.json, and the schemas only they use, are
// left out: the SDK has no methods for them yet.
// Run with `npm run generate`; commit both files.
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { parse, stringify } from "yaml";

const spec = "spec/public-api.yaml";
const bin = process.platform === "win32" ? "npx.cmd" : "npx";
const methods = ["get", "post", "put", "patch", "delete"];

const doc = parse(readFileSync(spec, "utf8"));
const skip = new Set(Object.keys(JSON.parse(readFileSync("scripts/not-in-sdk.json", "utf8"))));

/** The component schemas `value` refers to, directly or through other schemas. */
function reachable(roots) {
  const seen = new Set();
  const visit = (value) => {
    if (Array.isArray(value)) return value.forEach(visit);
    if (!value || typeof value !== "object") return;
    const ref = value.$ref;
    if (typeof ref === "string" && ref.startsWith("#/components/schemas/")) {
      const name = ref.slice("#/components/schemas/".length);
      if (!seen.has(name)) {
        seen.add(name);
        visit(doc.components.schemas[name]);
      }
    }
    for (const v of Object.values(value)) visit(v);
  };
  roots.forEach(visit);
  return seen;
}

const kept = [];
const skipped = [];
for (const [route, item] of Object.entries(doc.paths ?? {})) {
  for (const method of methods) {
    const op = item[method];
    if (!op) continue;
    if (skip.has(op.operationId)) {
      skipped.push(op);
      delete item[method];
    } else {
      kept.push(op);
    }
  }
  if (!methods.some((m) => item[m])) delete doc.paths[route];
}
const keptSchemas = reachable(kept);
for (const name of reachable(skipped)) {
  if (!keptSchemas.has(name)) delete doc.components.schemas[name];
}

const dir = mkdtempSync(join(tmpdir(), "pantech-js-"));
try {
  const pruned = join(dir, "public-api.yaml");
  writeFileSync(pruned, stringify(doc, { lineWidth: 0 }));
  execFileSync(bin, ["openapi-typescript", pruned, "--default-non-nullable", "false", "-o", "src/types.gen.ts"], {
    stdio: "inherit",
  });
} finally {
  rmSync(dir, { recursive: true, force: true });
}

// Schemas the SDK widens by hand in src/models.ts (fields the API sends that
// the spec does not describe yet). Everything else is aliased as is.
const handWritten = new Set(["Me"]);

const names = Object.keys(doc.components?.schemas ?? {}).filter((n) => !handWritten.has(n));
const lines = [
  "// Generated by scripts/generate.mjs from spec/public-api.yaml. Do not edit.",
  'import type { components } from "./types.gen.js";',
  "",
  ...names.map((n) => `export type ${n} = components["schemas"]["${n}"];`),
  "",
];
writeFileSync("src/models.gen.ts", lines.join("\n"));

execFileSync(bin, ["biome", "format", "--write", "src/types.gen.ts", "src/models.gen.ts"], { stdio: "inherit" });
